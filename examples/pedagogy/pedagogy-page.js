function v4SeedTilt(seed) {
  return Math.atan2(Math.hypot(seed[0], seed[1]), seed[2]) * 180 / Math.PI;
}

function frameV4Preset(renderer, presetId, defaultFov) {
  // Finish pending orbit damping before explicitly placing the camera. Otherwise
  // a later radius edit can resume that old movement in a paused figure.
  const damping = renderer.controls.enableDamping;
  renderer.controls.enableDamping = false;
  renderer.controls.update();
  renderer.controls.enableDamping = damping;
  // Keep the standard oblique, z-up framing for the general 3D lesson.
  renderer.camera.fov = defaultFov;
  renderer.camera.updateProjectionMatrix();
  renderer.camera.up.set(0, 0, 1);
  renderer.fitView();

  const view = V4_PRESET_CAMERA_VIEWS[presetId];
  if (!view) return;

  // Crossed loops was composed in the historical V4 front view: the camera
  // looks from +Z toward the carrier center, with +Y at the top of the screen.
  const target = renderer.controls.target;
  const distance = view.distance ?? renderer.camera.position.distanceTo(target);
  const directionLength = Math.hypot(...view.direction);
  const [dx, dy, dz] = view.direction.map((value) => value / directionLength);
  renderer.camera.fov = view.fov ?? defaultFov;
  renderer.camera.updateProjectionMatrix();
  renderer.camera.up.set(...view.up);
  renderer.camera.position.set(
    target.x + dx * distance,
    target.y + dy * distance,
    target.z + dz * distance,
  );
  renderer.camera.lookAt(target);
  renderer.controls.update();
  renderer.controls.saveState();
}

