function updateOutput(input, digits = null) {
  const output = root.querySelector(`output[for="${input.id}"]`);
  if (!output) return;
  const number = Number(input.value);
  output.value = digits === null ? input.value : number.toFixed(digits);
}

function bindRange(id, callback, digits = null) {
  const input = root.querySelector(`#${id}`);
  const update = () => {
    updateOutput(input, digits);
    callback(Number(input.value), input);
    syncRangeStepButtons(input);
  };
  input.addEventListener("input", update);
  root.querySelectorAll(`[data-step-for="${id}"]`).forEach((button) => {
    button.addEventListener("click", () => {
      if (button.dataset.stepDirection === "down") input.stepDown();
      else input.stepUp();
      input.dispatchEvent(new Event("input", { bubbles: true }));
    });
  });
  updateOutput(input, digits);
  syncRangeStepButtons(input);
  return input;
}

function syncRangeStepButtons(input) {
  const value = Number(input.value);
  const minimum = Number(input.min);
  const maximum = Number(input.max);
  const down = root.querySelector(`[data-step-for="${input.id}"][data-step-direction="down"]`);
  const up = root.querySelector(`[data-step-for="${input.id}"][data-step-direction="up"]`);
  if (down) down.disabled = value <= minimum;
  if (up) up.disabled = value >= maximum;
}

function installBackgroundDragScroll(panel) {
  const interactive = "a, button, input, select, textarea, label, summary, canvas, [role='button']";
  let drag = null;

  panel.addEventListener("pointerdown", (event) => {
    if (event.pointerType === "touch" || event.button !== 0 || !event.isPrimary) return;
    if (getComputedStyle(panel).overflowY === "hidden") return;
    if (event.target.closest(interactive) || panel.scrollHeight <= panel.clientHeight + 1) return;
    drag = {
      pointerId: event.pointerId,
      startY: event.clientY,
      scrollTop: panel.scrollTop,
      moved: false,
    };
    panel.setPointerCapture(event.pointerId);
  });

  panel.addEventListener("pointermove", (event) => {
    if (!drag || event.pointerId !== drag.pointerId) return;
    const delta = event.clientY - drag.startY;
    if (!drag.moved && Math.abs(delta) < 4) return;
    drag.moved = true;
    panel.classList.add("is-dragging");
    panel.scrollTop = drag.scrollTop - delta;
    event.preventDefault();
  });

  const finish = (event) => {
    if (!drag || (event.pointerId !== undefined && event.pointerId !== drag.pointerId)) return;
    const pointerId = drag.pointerId;
    drag = null;
    panel.classList.remove("is-dragging");
    if (panel.hasPointerCapture(pointerId)) panel.releasePointerCapture(pointerId);
  };
  panel.addEventListener("pointerup", finish);
  panel.addEventListener("pointercancel", finish);
  panel.addEventListener("lostpointercapture", finish);
}

function installClock(render, { initialTime = 0, period = TAU } = {}) {
  const timeInput = root.querySelector("#lesson-time");
  const speedInput = root.querySelector("#lesson-speed");
  const playButton = root.querySelector('[data-clock="play"]');
  const resetButton = root.querySelector('[data-clock="reset"]');
  const query = new URLSearchParams(location.search);
  const requestedTime = Number(query.get("time") ?? initialTime);
  const prefersReducedMotion = matchMedia("(prefers-reduced-motion: reduce)");
  const validPeriod = (value) => {
    const numeric = Number(value);
    return Number.isFinite(numeric) && numeric > 1e-12 ? numeric : TAU;
  };
  const wrap = (value, cycle) => {
    const wrapped = ((value % cycle) + cycle) % cycle;
    return Math.abs(wrapped - cycle) <= 1e-12 ? 0 : wrapped;
  };
  const initialPeriod = validPeriod(period);
  const state = {
    time: wrap(Number.isFinite(requestedTime) ? requestedTime : initialTime, initialPeriod),
    period: initialPeriod,
    speed: Number(speedInput.value),
    playing: query.get("paused") !== "1" &&
      (query.get("autoplay") === "1" || !prefersReducedMotion.matches),
    previousTimestamp: null,
    disposed: false,
    frameRequest: null,
    renderCount: 0,
  };

  function sync() {
    timeInput.max = String(state.period);
    timeInput.value = String(state.time);
    state.time = Number(timeInput.value);
    root.querySelector('output[for="lesson-time"]').value = state.time.toFixed(2);
    root.querySelector('output[for="lesson-speed"]').value = state.speed.toFixed(2);
    playButton.textContent = state.playing ? "Pause" : "Play";
    playButton.setAttribute("aria-label", state.playing ? "Pause animation" : "Play animation");
    playButton.removeAttribute("aria-pressed");
    root.dataset.clockPlaying = String(state.playing);
    root.dataset.clockPeriod = String(state.period);
    root.dataset.clockTime = String(state.time);
  }

  function syncUrl() {
    const url = new URL(location.href);
    const compactTime = Number(state.time.toFixed(6)).toString();
    url.searchParams.set("time", compactTime);
    if (state.playing) {
      url.searchParams.delete("paused");
      url.searchParams.set("autoplay", "1");
    } else {
      url.searchParams.set("paused", "1");
      url.searchParams.delete("autoplay");
    }
    history.replaceState(null, "", url);
  }

  function renderCurrent() {
    render(state.time);
    state.renderCount += 1;
    root.dataset.clockRenderCount = String(state.renderCount);
  }

  function requestNextFrame() {
    if (!state.disposed && state.playing && state.frameRequest === null) {
      state.frameRequest = requestAnimationFrame(frame);
    }
  }

  timeInput.addEventListener("input", () => {
    state.time = Math.min(state.period, Math.max(0, Number(timeInput.value)));
    state.playing = false;
    state.previousTimestamp = null;
    sync();
    syncUrl();
    renderCurrent();
  });
  speedInput.addEventListener("input", () => {
    state.speed = Number(speedInput.value);
    sync();
  });
  playButton.addEventListener("click", () => {
    state.playing = !state.playing;
    state.previousTimestamp = null;
    sync();
    syncUrl();
    requestNextFrame();
  });
  resetButton.addEventListener("click", () => {
    state.time = wrap(initialTime, state.period);
    state.playing = false;
    state.previousTimestamp = null;
    sync();
    syncUrl();
    renderCurrent();
  });

  function frame(timestamp) {
    state.frameRequest = null;
    if (state.disposed) return;
    if (state.previousTimestamp === null) state.previousTimestamp = timestamp;
    const delta = Math.min(0.1, Math.max(0, (timestamp - state.previousTimestamp) / 1000));
    state.previousTimestamp = timestamp;
    if (!state.playing) return;
    state.time = wrap(state.time + delta * state.speed, state.period);
    sync();
    renderCurrent();
    requestNextFrame();
  }

  const onReducedMotionChange = (event) => {
    if (!event.matches || query.get("autoplay") === "1" || !state.playing) return;
    state.playing = false;
    state.previousTimestamp = null;
    sync();
    syncUrl();
  };
  prefersReducedMotion.addEventListener?.("change", onReducedMotionChange);

  let resizeQueued = false;
  const resizeObserver = typeof ResizeObserver === "function"
    ? new ResizeObserver(() => {
      if (resizeQueued || state.disposed) return;
      resizeQueued = true;
      requestAnimationFrame(() => {
        resizeQueued = false;
        if (!state.disposed) renderCurrent();
      });
    })
    : null;
  resizeObserver?.observe(root);

  sync();
  syncUrl();
  renderCurrent();
  requestNextFrame();
  return {
    get time() { return state.time; },
    get period() { return state.period; },
    get playing() { return state.playing; },
    renderNow() { renderCurrent(); },
    setPeriod(nextPeriod, { preservePhase = true } = {}) {
      const normalized = state.period > 0 ? state.time / state.period : 0;
      state.period = validPeriod(nextPeriod);
      state.time = preservePhase
        ? Math.min(state.period, Math.max(0, normalized * state.period))
        : wrap(state.time, state.period);
      state.previousTimestamp = null;
      sync();
      syncUrl();
      renderCurrent();
    },
    dispose() {
      state.disposed = true;
      if (state.frameRequest !== null) cancelAnimationFrame(state.frameRequest);
      resizeObserver?.disconnect();
      prefersReducedMotion.removeEventListener?.("change", onReducedMotionChange);
    },
  };
}

function prepareCanvas(canvas, background = "#fbfbf8") {
  const rectangle = canvas.getBoundingClientRect();
  const width = Math.max(1, Math.round(rectangle.width || 640));
  const height = Math.max(1, Math.round(rectangle.height || 480));
  const dpr = Math.min(2, Math.max(1, devicePixelRatio || 1));
  if (canvas.width !== Math.round(width * dpr) || canvas.height !== Math.round(height * dpr)) {
    canvas.width = Math.round(width * dpr);
    canvas.height = Math.round(height * dpr);
  }
  const context = canvas.getContext("2d");
  context.setTransform(dpr, 0, 0, dpr, 0, 0);
  context.fillStyle = background;
  context.fillRect(0, 0, width, height);
  return { context, width, height };
}

function pointColor(index, count) {
  return `hsl(${Math.round((330 * index) / Math.max(1, count))} 72% 46%)`;
}

function radialView(canvas, model, time, {
  connect = true,
  showPaths = true,
  highlight = -1,
  pointSize = 4.2,
  title = "Radial view",
} = {}) {
  const { context, width, height } = prepareCanvas(canvas);
  canvas.dataset.pointSize = String(pointSize);
  canvas.dataset.highlightedPointIndex = String(highlight);
  canvas.dataset.showPaths = String(showPaths);
  canvas.dataset.connect = String(connect);
  const displacementExtent = Math.max(
    1,
    (model.amplitude ?? 1) + Math.abs(model.amplitudeShift ?? 0),
  );
  const scale = Math.min(width, height) * 0.39 /
    (model.config.radius * displacementExtent);
  const center = [width / 2, height / 2 + 8];
  const screen = ([x, y]) => [
    center[0] + (x - model.config.center[0]) * scale,
    center[1] - (y - model.config.center[1]) * scale,
  ];
  context.fillStyle = "#33404c";
  context.font = "600 13px system-ui, sans-serif";
  context.fillText(title, 14, 22);
  context.beginPath();
  context.arc(center[0], center[1], model.config.radius * scale, 0, TAU);
  context.strokeStyle = "rgba(34, 45, 57, 0.7)";
  context.lineWidth = 1.3;
  context.stroke();

  if (showPaths) {
    const sparsePaths = model.paths.length <= 4;
    context.strokeStyle = `rgba(42, 54, 69, ${sparsePaths ? 0.34 : 0.16})`;
    context.lineWidth = sparsePaths ? 1.35 : 1;
    for (const path of model.paths) {
      context.beginPath();
      if (path.type === "circle") {
        const pathCenter = screen(path.center);
        context.arc(pathCenter[0], pathCenter[1], path.radius * scale, 0, TAU);
      } else {
        const start = screen(path.start);
        const end = screen(path.end);
        context.moveTo(...start);
        context.lineTo(...end);
      }
      context.stroke();
    }
  }

  const points = model.sample(time);
  if (connect && points.length > 1) {
    context.beginPath();
    points.forEach((point, index) => {
      const position = screen(point.position);
      if (index === 0) context.moveTo(...position);
      else context.lineTo(...position);
    });
    context.closePath();
    context.strokeStyle = "rgba(14, 77, 108, 0.78)";
    context.lineWidth = 2;
    context.stroke();
  }
  points.forEach((point, index) => {
    const position = screen(point.position);
    const radius = index === highlight
      ? Math.max(pointSize + 2.8, pointSize * 1.4)
      : pointSize;
    context.beginPath();
    context.arc(position[0], position[1], radius, 0, TAU);
    context.fillStyle = index === highlight ? "#c33f2f" : pointColor(index, points.length);
    context.fill();
    context.strokeStyle = "rgba(255,255,255,0.85)";
    context.stroke();
  });
  return points;
}

function drawLineVelocityPlot(canvas, model, time, motionProfile, selectedPointIndex = 0) {
  const { context, width, height } = prepareCanvas(canvas, "#ffffff");
  const angularSpeed = Math.abs(model.config.angularSpeed);
  const period = angularSpeed > 1e-12 ? TAU / angularSpeed : TAU;
  const amplitude = model.amplitude ?? 1;
  const peakVelocity = model.config.radius * amplitude * angularSpeed;
  const velocityLimit = peakVelocity > 1e-12 ? peakVelocity : 1;
  const selectedIndex = Math.max(0, Math.min(
    Math.round(selectedPointIndex),
    model.paths.length - 1,
  ));
  const selectedPhase = model.config.phase.winding * model.paths[selectedIndex].theta;
  const velocityAt = (sampleTime) => {
    const velocity = lineSignedVelocityAtTime(
      motionProfile,
      model.config,
      sampleTime,
      selectedPhase,
      amplitude,
    );
    return velocity;
  };
  const margins = {
    left: width < 240 ? 36 : 43,
    right: 10,
    top: 12,
    bottom: 34,
  };
  const plotWidth = Math.max(1, width - margins.left - margins.right);
  const plotHeight = Math.max(1, height - margins.top - margins.bottom);
  const xFor = (sampleTime) => margins.left + (sampleTime / period) * plotWidth;
  const wrapPlotTime = (sampleTime) => ((sampleTime % period) + period) % period;
  const yFor = (velocity) => margins.top +
    (0.5 - velocity / (2 * velocityLimit)) * plotHeight;

  context.strokeStyle = "rgba(42, 54, 69, 0.14)";
  context.lineWidth = 1;
  for (const fraction of [0, 0.25, 0.5, 0.75, 1]) {
    const x = margins.left + fraction * plotWidth;
    context.beginPath();
    context.moveTo(x, margins.top);
    context.lineTo(x, margins.top + plotHeight);
    context.stroke();
  }
  for (const fraction of [0, 0.5, 1]) {
    const y = margins.top + fraction * plotHeight;
    context.beginPath();
    context.moveTo(margins.left, y);
    context.lineTo(margins.left + plotWidth, y);
    context.stroke();
  }

  context.strokeStyle = "rgba(23, 32, 42, 0.72)";
  context.lineWidth = 1.1;
  context.beginPath();
  context.moveTo(margins.left, margins.top);
  context.lineTo(margins.left, margins.top + plotHeight);
  context.moveTo(margins.left, yFor(0));
  context.lineTo(margins.left + plotWidth, yFor(0));
  context.stroke();

  context.strokeStyle = "#146c94";
  context.lineWidth = 2.2;
  canvas.dataset.reversalTimes = "";
  if (motionProfile === "harmonic") {
    context.beginPath();
    const steps = Math.max(80, Math.round(plotWidth));
    for (let index = 0; index <= steps; index += 1) {
      const sampleTime = (period * index) / steps;
      const velocity = velocityAt(sampleTime);
      const x = xFor(sampleTime);
      const y = yFor(velocity);
      if (index === 0) context.moveTo(x, y);
      else context.lineTo(x, y);
    }
    context.stroke();
  } else {
    const phaseAtStart = -selectedPhase;
    const phaseAtEnd = model.config.angularSpeed * period - selectedPhase;
    const minimumPhase = Math.min(phaseAtStart, phaseAtEnd);
    const maximumPhase = Math.max(phaseAtStart, phaseAtEnd);
    const firstInteger = Math.ceil(minimumPhase / Math.PI - 1e-12);
    const lastInteger = Math.floor(maximumPhase / Math.PI + 1e-12);
    const reversalTimes = [];
    if (Math.abs(model.config.angularSpeed) > 1e-12) {
      for (let integer = firstInteger; integer <= lastInteger; integer += 1) {
        const reversalTime = (selectedPhase + integer * Math.PI) / model.config.angularSpeed;
        if (reversalTime >= -1e-10 && reversalTime <= period + 1e-10) {
          const clamped = Math.min(period, Math.max(0, reversalTime));
          if (!reversalTimes.some((existing) => Math.abs(existing - clamped) <= 1e-9)) {
            reversalTimes.push(clamped);
          }
        }
      }
    }
    reversalTimes.sort((a, b) => a - b);
    const boundaries = [0, ...reversalTimes.filter((value) => value > 1e-9 && value < period - 1e-9), period];
    for (let index = 0; index < boundaries.length - 1; index += 1) {
      const start = boundaries[index];
      const end = boundaries[index + 1];
      const velocity = velocityAt((start + end) / 2);
      context.beginPath();
      context.moveTo(xFor(start), yFor(velocity));
      context.lineTo(xFor(end), yFor(velocity));
      context.stroke();
    }
    const epsilon = Math.max(period * 1e-7, 1e-9);
    for (const reversalTime of reversalTimes) {
      const limitingVelocities = [
        velocityAt(wrapPlotTime(reversalTime - epsilon, period)),
        velocityAt(wrapPlotTime(reversalTime + epsilon, period)),
      ].filter((velocity, index, values) => velocity !== null &&
        values.findIndex((candidate) => Math.abs(candidate - velocity) <= 1e-9) === index);
      for (const velocity of limitingVelocities) {
        context.beginPath();
        context.arc(xFor(reversalTime), yFor(velocity), 3, 0, TAU);
        context.fillStyle = "white";
        context.fill();
        context.strokeStyle = "#146c94";
        context.lineWidth = 1.4;
        context.stroke();
      }
    }
    canvas.dataset.reversalTimes = reversalTimes.map((value) => value.toFixed(6)).join(",");
  }

  const wrappedTime = ((time % period) + period) % period;
  const currentVelocity = velocityAt(wrappedTime);
  const currentX = xFor(wrappedTime);
  context.strokeStyle = "rgba(195, 63, 47, 0.34)";
  context.lineWidth = 1;
  context.beginPath();
  context.moveTo(currentX, margins.top);
  context.lineTo(currentX, margins.top + plotHeight);
  context.stroke();
  if (currentVelocity !== null) {
    context.beginPath();
    context.arc(currentX, yFor(currentVelocity), 4.3, 0, TAU);
    context.fillStyle = "#c33f2f";
    context.fill();
    context.strokeStyle = "white";
    context.lineWidth = 1.2;
    context.stroke();
  }

  context.fillStyle = "#5d6873";
  context.font = "10px system-ui, sans-serif";
  context.textAlign = "center";
  context.fillText("0", margins.left, height - 19);
  context.fillText("T/2", margins.left + plotWidth / 2, height - 19);
  context.fillText("T", margins.left + plotWidth, height - 19);
  context.fillStyle = "#33404c";
  context.font = "600 10px system-ui, sans-serif";
  context.fillText("time t", margins.left + plotWidth / 2, height - 5);
  context.textAlign = "right";
  context.font = "10px system-ui, sans-serif";
  const amplitudeSymbol = amplitude === 1 ? "" : "A";
  context.fillText(`+${amplitudeSymbol}R|ω|`, margins.left - 5, margins.top + 3);
  context.fillText("0", margins.left - 5, yFor(0) + 3);
  context.fillText(`−${amplitudeSymbol}R|ω|`, margins.left - 5, margins.top + plotHeight + 3);
  if (motionProfile === "constant-speed") {
    context.fillStyle = "#0e4d6c";
    context.font = "600 9px system-ui, sans-serif";
    context.textAlign = "right";
    const magnitude = (2 * peakVelocity) / Math.PI;
    context.fillText(`+2${amplitudeSymbol}R|ω|/π`, margins.left + plotWidth - 4, yFor(magnitude) - 5);
    context.fillText(`−2${amplitudeSymbol}R|ω|/π`, margins.left + plotWidth - 4, yFor(-magnitude) + 11);
  }
  context.save();
  context.translate(10, margins.top + plotHeight / 2);
  context.rotate(-Math.PI / 2);
  context.textAlign = "center";
  context.font = "600 10px system-ui, sans-serif";
  context.fillText("signed velocity", 0, 0);
  context.restore();

  canvas.dataset.motionProfile = motionProfile;
  canvas.dataset.currentVelocity = currentVelocity === null ? "" : String(currentVelocity);
  canvas.dataset.normalizedVelocity = currentVelocity === null || peakVelocity <= 1e-12
    ? ""
    : String(currentVelocity / peakVelocity);
  canvas.dataset.velocityMinimum = String(-peakVelocity);
  canvas.dataset.velocityMaximum = String(peakVelocity);
  canvas.dataset.period = String(period);
  canvas.dataset.velocityDefined = String(currentVelocity !== null);
  canvas.dataset.selectedPointIndex = String(selectedIndex);
}

function barView(canvas, model, time, {
  highlight = -1,
  pointSize = 4.2,
  showPaths = true,
  connect = true,
  title = "",
} = {}) {
  const { context, width, height } = prepareCanvas(canvas);
  canvas.dataset.pointSize = String(pointSize);
  canvas.dataset.highlightedPointIndex = String(highlight);
  canvas.dataset.showPaths = String(showPaths);
  canvas.dataset.connect = String(connect);
  const points = model.sample(time);
  const left = 42;
  const right = 18;
  const top = 28;
  const bottom = height - 44;
  const middle = (top + bottom) / 2;
  const half = (bottom - top) / 2;
  if (title) {
    context.fillStyle = "#33404c";
    context.font = "600 13px system-ui, sans-serif";
    context.fillText(title, 14, 20);
  }
  context.strokeStyle = "rgba(42, 54, 69, 0.16)";
  context.lineWidth = 1;
  context.beginPath();
  context.moveTo(left, middle);
  context.lineTo(width - right, middle);
  context.stroke();

  context.fillStyle = "#5d6873";
  context.font = "10px system-ui, sans-serif";
  context.textAlign = "right";
  const verticalExtent = Math.max(
    1,
    (model.amplitude ?? 1) + Math.abs(model.amplitudeShift ?? 0),
  );
  const extentLabel = Number(verticalExtent.toFixed(2)).toString();
  context.fillText(`+${extentLabel}`, left - 7, top + 3);
  context.fillText("0", left - 7, middle + 3);
  context.fillText(`−${extentLabel}`, left - 7, bottom + 3);
  context.save();
  context.translate(11, middle);
  context.rotate(-Math.PI / 2);
  context.textAlign = "center";
  context.font = "600 10px system-ui, sans-serif";
  context.fillText("signed displacement ρᵢ/R", 0, 0);
  context.restore();
  context.textAlign = "center";
  context.font = "600 10px system-ui, sans-serif";
  context.fillText("sample index i", (left + width - right) / 2, height - 9);
  context.textAlign = "start";

  const positions = [];
  points.forEach((point, index) => {
    const x = left + ((width - left - right) * (index + 0.5)) / points.length;
    const normalized = point.signedRadius / model.config.radius / verticalExtent;
    const y = middle - normalized * half;
    positions.push([x, y]);
    if (showPaths) {
      context.beginPath();
      context.moveTo(x, top);
      context.lineTo(x, bottom);
      context.strokeStyle = "rgba(42, 54, 69, 0.17)";
      context.stroke();
    }
    context.beginPath();
    const radius = index === highlight
      ? Math.max(pointSize + 2.8, pointSize * 1.4)
      : pointSize;
    context.arc(x, y, radius, 0, TAU);
    context.fillStyle = index === highlight ? "#c33f2f" : pointColor(index, points.length);
    context.fill();
  });
  if (connect && positions.length > 1) {
    context.beginPath();
    positions.forEach((position, index) => index === 0 ? context.moveTo(...position) : context.lineTo(...position));
    context.strokeStyle = "rgba(14, 77, 108, 0.68)";
    context.lineWidth = 1.7;
    context.stroke();
  }
  return points;
}

