function equationContent(meta) {
  const formulas = meta.equations
    .map((equation) => {
      if (typeof equation === "string") {
        return `<p class="equation-formula">${equation}</p>`;
      }
      return `<p class="equation-formula">${equation.formula}</p><p class="equation-explanation">${equation.explanation}</p>`;
    })
    .join("");
  const terms = (meta.terms ?? [])
    .map(([symbol, meaning]) => `<div><dt>${symbol}</dt><dd>${meaning}</dd></div>`)
    .join("");
  return { formulas, terms };
}

