  let clock;
  const manualZoomEnabled = renderer.controls.enableZoom;
  const manualPanEnabled = renderer.controls.enablePan;

  function fitToScreen() {
    renderer.resize();
    const { camera, controls } = renderer;
    // Finish any pending orbit movement before preserving the chosen direction.
    const damping = controls.enableDamping;
    controls.enableDamping = false;
    controls.update();
    controls.enableDamping = damping;
    const direction = camera.position.clone().sub(controls.target);
    if (direction.lengthSq() < 1e-12) direction.set(1.15, -1.35, 0.9);
    direction.normalize();

    // Bound the entire motion cycle, so playback does not cause zoom pumping.
    // Include the slightly expanded sphere outlines and a screen-space margin
    // for the markers. The narrower field of view controls portrait fitting.
    const radius = Math.max(1e-3, state.carrierRadius + state.localRadius * (state.showSpheres ? 1.018 : 1));
    const verticalHalfFov = Math.atan(Math.tan(camera.fov * Math.PI / 360) / camera.zoom);
    const horizontalHalfFov = Math.atan(Math.tan(verticalHalfFov) * camera.aspect);
    const halfFov = Math.min(verticalHalfFov, horizontalHalfFov);
    const screenSize = Math.max(1, Math.min(renderer.canvas.clientWidth, renderer.canvas.clientHeight));
    const fill = Math.max(0.2, 0.92 - (state.pointSize + 3) / screenSize);
    const distance = radius / Math.sin(Math.atan(Math.tan(halfFov) * fill));
    controls.target.fromArray(model.config.center);
    camera.position.copy(direction).multiplyScalar(distance).add(controls.target);
    camera.near = Math.max(radius / 1000, 1e-6);
    camera.far = Math.max(radius * 100, distance * 4);
    camera.updateProjectionMatrix();
    controls.minDistance = radius * 0.1;
    controls.maxDistance = Math.max(radius * 50, distance * 2);
    controls.update();
    controls.saveState();
    syncCameraDataset();
  }

