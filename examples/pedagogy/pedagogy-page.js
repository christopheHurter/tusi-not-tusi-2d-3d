    renderer.canvas.dataset.cameraTarget = renderer.controls.target.toArray().map((value) => value.toFixed(6)).join(",");
    renderer.canvas.dataset.cameraUp = renderer.camera.up.toArray().join(",");
    renderer.canvas.dataset.cameraFov = String(renderer.camera.fov);
