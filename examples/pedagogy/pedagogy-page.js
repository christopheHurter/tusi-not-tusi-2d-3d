  function createCurve(points, color, name) {
    const positions = new Float32Array(points.length * 3);
    points.forEach((point, index) => positions.set(point, index * 3));
    const geometry = new BufferGeometry();
    geometry.setAttribute("position", new BufferAttribute(positions, 3));
    const material = new LineBasicMaterial({
      color,
      transparent: true,
      opacity: 0.7,
      depthWrite: false,
    });
    const curve = new LineLoop(geometry, material);
    curve.name = name;
    return curve;
  }

  function rebuildReferenceGuides() {
    disposeGroupChildren(guideGroup);
    const sphereSurface = new SphereGeometry(state.radius, 18, 12);
    const sphereWireframe = new WireframeGeometry(sphereSurface);
    sphereSurface.dispose();
    const sphere = new LineSegments(sphereWireframe, new LineBasicMaterial({
      color: "#64748b",
      transparent: true,
      opacity: 0.24,
      depthWrite: false,
    }));
    sphere.name = "reference-sphere";
    const center = model.config.center ?? [0, 0, 0];
    sphere.position.set(center[0], center[1], center[2]);
    guideGroup.add(sphere);
    let positiveEndpoints = model.paths.map((path) => path.end);
    let negativeEndpoints = model.paths.map((path) => path.start);
    if (state.geometryMode === "lissajous" || state.geometryMode === "epicycle") {
      // N samples the moving balls, not the construction curve. Keep the
      // spherical guides smooth, even with few balls or many curve cycles.
      // These buffers are rebuilt on parameter edits, never during playback.
      const segments = state.geometryMode === "lissajous"
        ? Math.max(256, 64 * Math.max(
          state.lissajousShape.horizontalCycles,
          state.lissajousShape.verticalCycles,
        ))
        : Math.max(256, 32 * (
          Math.abs(state.epicycleShape.carrierTurns)
          + Math.abs(state.epicycleShape.epicycleTurns)
        ));
      const directionAt = state.geometryMode === "lissajous"
        ? (parameter) => lissajousDiameterDirection(parameter, state.lissajousShape)
        : (parameter) => epicycleDiameterDirection(parameter, state.epicycleShape);
      const destinationOffset = state.geometryMode === "epicycle"
        ? state.epicycleShape.destinationPhaseDegrees * Math.PI / 180
        : 0;
      const originDirections = Array.from({ length: segments }, (_, index) =>
        directionAt(TAU * index / segments));
      const destinationDirections = destinationOffset === 0
        ? originDirections
        : Array.from({ length: segments }, (_, index) =>
          directionAt(TAU * index / segments + destinationOffset));
      positiveEndpoints = destinationDirections.map((direction) => center.map((coordinate, axis) =>
        coordinate + state.radius * direction[axis]));
      negativeEndpoints = originDirections.map((direction) => center.map((coordinate, axis) =>
        coordinate - state.radius * direction[axis]));
    }
    guideGroup.add(createCurve(positiveEndpoints, "#38bdf8", "positive-endpoint-curve"));
    guideGroup.add(createCurve(negativeEndpoints, "#fb7185", "negative-endpoint-curve"));
    renderer.canvas.dataset.endpointCurveSampleCount = String(positiveEndpoints.length);
    syncReferenceGuideVisibility();
  }

